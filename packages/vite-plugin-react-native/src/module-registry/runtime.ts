/**
 * Metro-compatible module registry runtime, written from scratch (no Metro
 * dependency). The prelude is emitted as the first lines of a
 * `moduleFormat: "metro"` bundle and provides:
 *
 * - `__d(factory, moduleId, dependencyMap)` module registration,
 * - `__r(moduleId)` module execution with caching,
 * - cycle tolerance via partially-initialized exports (a module is marked
 *   initialized before its factory runs, so circular requires observe the
 *   exports object filled so far),
 * - `__r.importDefault(moduleId)` / `__r.importAll(moduleId)` interop helpers
 *   matching metro-runtime semantics (`__esModule` handling),
 * - `__c()` registry reset, mirroring metro-runtime's `clear()`.
 *
 * Factories are invoked with the canonical Metro argument list
 * `(global, require, importDefault, importAll, module, exports, dependencyMap)`
 * so tooling that wraps module bodies (for example react-refresh glue) keeps
 * working. The code is plain ES5-style script code that Hermes can evaluate
 * directly: no import/export statements, no `import.meta`, no top-level await.
 */
export const MODULE_REGISTRY_PRELUDE = [
  "(function (global) {",
  '  "use strict";',
  "",
  "  if (global.__d != null && global.__r != null) {",
  "    return;",
  "  }",
  "",
  "  var EMPTY = {};",
  "  var modules = Object.create(null);",
  "",
  "  function define(factory, moduleId, dependencyMap) {",
  "    if (modules[moduleId] != null) {",
  "      return;",
  "    }",
  "    modules[moduleId] = {",
  "      dependencyMap: dependencyMap,",
  "      error: undefined,",
  "      factory: factory,",
  "      hasError: false,",
  "      importedAll: EMPTY,",
  "      importedDefault: EMPTY,",
  "      isInitialized: false,",
  "      publicModule: { exports: {} },",
  "    };",
  "  }",
  "",
  "  function metroRequire(moduleId) {",
  "    var module = modules[moduleId];",
  "    return module && module.isInitialized",
  "      ? module.publicModule.exports",
  "      : guardedLoadModule(moduleId, module);",
  "  }",
  "",
  "  function metroImportDefault(moduleId) {",
  "    var module = modules[moduleId];",
  "    if (module && module.importedDefault !== EMPTY) {",
  "      return module.importedDefault;",
  "    }",
  "    var exports = metroRequire(moduleId);",
  "    var importedDefault = exports && exports.__esModule ? exports.default : exports;",
  "    modules[moduleId].importedDefault = importedDefault;",
  "    return importedDefault;",
  "  }",
  "",
  "  function metroImportAll(moduleId) {",
  "    var module = modules[moduleId];",
  "    if (module && module.importedAll !== EMPTY) {",
  "      return module.importedAll;",
  "    }",
  "    var exports = metroRequire(moduleId);",
  "    var importedAll;",
  "    if (exports && exports.__esModule) {",
  "      importedAll = exports;",
  "    } else {",
  "      importedAll = {};",
  "      if (exports) {",
  "        for (var key in exports) {",
  "          if (Object.prototype.hasOwnProperty.call(exports, key)) {",
  "            importedAll[key] = exports[key];",
  "          }",
  "        }",
  "      }",
  "      importedAll.default = exports;",
  "    }",
  "    modules[moduleId].importedAll = importedAll;",
  "    return importedAll;",
  "  }",
  "",
  "  function guardedLoadModule(moduleId, module) {",
  "    if (!module) {",
  "      throw new Error('Requiring unknown module \"' + moduleId + '\".');",
  "    }",
  "    if (module.hasError) {",
  "      throw module.error;",
  "    }",
  "    return loadModuleImplementation(moduleId, module);",
  "  }",
  "",
  "  function loadModuleImplementation(moduleId, module) {",
  "    module.isInitialized = true;",
  "    var moduleObject = module.publicModule;",
  "    moduleObject.id = moduleId;",
  "    var factory = module.factory;",
  "    var dependencyMap = module.dependencyMap;",
  "    try {",
  "      factory(",
  "        global,",
  "        metroRequire,",
  "        metroImportDefault,",
  "        metroImportAll,",
  "        moduleObject,",
  "        moduleObject.exports,",
  "        dependencyMap,",
  "      );",
  "      module.factory = undefined;",
  "      module.dependencyMap = undefined;",
  "      return moduleObject.exports;",
  "    } catch (error) {",
  "      module.isInitialized = false;",
  "      module.hasError = true;",
  "      module.error = error;",
  "      module.publicModule = { exports: {} };",
  "      throw error;",
  "    }",
  "  }",
  "",
  "  function clear() {",
  "    modules = Object.create(null);",
  "  }",
  "",
  "  metroRequire.importDefault = metroImportDefault;",
  "  metroRequire.importAll = metroImportAll;",
  "",
  "  global.__d = define;",
  "  global.__r = metroRequire;",
  "  global.__c = clear;",
  "})(",
  '  typeof globalThis !== "undefined"',
  "    ? globalThis",
  '    : typeof global !== "undefined"',
  "      ? global",
  "      : this",
  ");",
  "",
].join("\n");
