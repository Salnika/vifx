/**
 * Metro-compatible module registry runtime, written from scratch (no Metro
 * dependency). The prelude is emitted as the first lines of a
 * `moduleFormat: "metro"` bundle and provides:
 *
 * - `__d(factory, moduleId, dependencyMap)` module registration,
 * - `__r(moduleId)` module execution with caching,
 * - cycle tolerance via partially-initialized exports (a module is marked
 *   initialized before its factory runs, so circular requires observe the
 *   exports object filled so far),
 * - `__r.importDefault(moduleId)` / `__r.importAll(moduleId)` interop helpers
 *   matching metro-runtime semantics (`__esModule` handling),
 * - `__c()` registry reset, mirroring metro-runtime's `clear()`.
 *
 * Factories are invoked with the canonical Metro argument list
 * `(global, require, importDefault, importAll, module, exports, dependencyMap)`
 * so tooling that wraps module bodies (for example react-refresh glue) keeps
 * working. The code is plain ES5-style script code that Hermes can evaluate
 * directly: no import/export statements, no `import.meta`, no top-level await.
 *
 * ## Fast Refresh (`hmr: true`)
 *
 * When built with `hmr: true` (development bundles only) the prelude
 * additionally ports Metro's Fast Refresh machinery from
 * `metro-runtime/src/polyfills/require.js`:
 *
 * - every module gets a `module.hot` object (`accept`/`dispose`);
 * - `$RefreshReg$` / `$RefreshSig$` are installed around each factory and the
 *   module's exports are registered with React Refresh afterwards, so
 *   `react-refresh/runtime` (exposed by RN's `setUpReactRefresh` at
 *   `global[__METRO_GLOBAL_PREFIX__ + "__ReactRefresh"]`) tracks component
 *   families — this replaces the per-module inline registration glue;
 * - `global.__accept` (metroHotUpdateModule) re-runs a changed module and
 *   bubbles the update up the inverse-dependency tree to the nearest React
 *   Refresh boundary, falling back to a full refresh when nothing accepts;
 * - `__d` routes a *re-definition* carrying `inverseDependencies` (the shape an
 *   HMR `update` delta uses) to `global.__accept`.
 *
 * All of this stays inert until React Refresh is installed and `global.__accept`
 * is actually called, so an `hmr: true` bundle still boots normally without a
 * connected HMR client. The `hmr: false` output is byte-identical to the
 * production prelude.
 */

export interface BuildModuleRegistryPreludeOptions {
  /**
   * Include Metro Fast Refresh machinery (`module.hot`, `global.__accept`,
   * React Refresh registration). Development bundles only. Default: `false`.
   */
  hmr?: boolean;
}

/**
 * Builds the module-registry runtime prelude. With `hmr: false` (the default)
 * the output is the lean production runtime; with `hmr: true` it additionally
 * carries the Fast Refresh engine described above.
 */
export function buildModuleRegistryPrelude(
  options: BuildModuleRegistryPreludeOptions = {},
): string {
  const hmr = options.hmr ?? false;

  return [
    "(function (global) {",
    '  "use strict";',
    "",
    "  if (global.__d != null && global.__r != null) {",
    "    return;",
    "  }",
    "",
    "  var EMPTY = {};",
    "  var modules = Object.create(null);",
    "",
    "  function define(factory, moduleId, dependencyMap) {",
    "    if (modules[moduleId] != null) {",
    ...(hmr
      ? [
          "      var inverseDependencies = arguments[4];",
          "      if (inverseDependencies && global.__accept != null) {",
          "        global.__accept(moduleId, factory, dependencyMap, inverseDependencies);",
          "      }",
        ]
      : []),
    "      return;",
    "    }",
    "    modules[moduleId] = {",
    "      dependencyMap: dependencyMap,",
    "      error: undefined,",
    "      factory: factory,",
    "      hasError: false,",
    ...(hmr ? ["      hot: createHotReloadingObject(),"] : []),
    "      importedAll: EMPTY,",
    "      importedDefault: EMPTY,",
    "      isInitialized: false,",
    "      publicModule: { exports: {} },",
    "    };",
    "  }",
    "",
    "  function metroRequire(moduleId) {",
    "    var module = modules[moduleId];",
    "    return module && module.isInitialized",
    "      ? module.publicModule.exports",
    "      : guardedLoadModule(moduleId, module);",
    "  }",
    "",
    "  function metroImportDefault(moduleId) {",
    "    var module = modules[moduleId];",
    "    if (module && module.importedDefault !== EMPTY) {",
    "      return module.importedDefault;",
    "    }",
    "    var exports = metroRequire(moduleId);",
    "    var importedDefault = exports && exports.__esModule ? exports.default : exports;",
    "    modules[moduleId].importedDefault = importedDefault;",
    "    return importedDefault;",
    "  }",
    "",
    "  function metroImportAll(moduleId) {",
    "    var module = modules[moduleId];",
    "    if (module && module.importedAll !== EMPTY) {",
    "      return module.importedAll;",
    "    }",
    "    var exports = metroRequire(moduleId);",
    "    var importedAll;",
    "    if (exports && exports.__esModule) {",
    "      importedAll = exports;",
    "    } else {",
    "      importedAll = {};",
    "      if (exports) {",
    "        for (var key in exports) {",
    "          if (Object.prototype.hasOwnProperty.call(exports, key)) {",
    "            importedAll[key] = exports[key];",
    "          }",
    "        }",
    "      }",
    "      importedAll.default = exports;",
    "    }",
    "    modules[moduleId].importedAll = importedAll;",
    "    return importedAll;",
    "  }",
    "",
    "  function guardedLoadModule(moduleId, module) {",
    "    if (!module) {",
    "      throw new Error('Requiring unknown module \"' + moduleId + '\".');",
    "    }",
    "    if (module.hasError) {",
    "      throw module.error;",
    "    }",
    "    return loadModuleImplementation(moduleId, module);",
    "  }",
    "",
    "  function loadModuleImplementation(moduleId, module) {",
    "    module.isInitialized = true;",
    "    var moduleObject = module.publicModule;",
    "    moduleObject.id = moduleId;",
    "    var factory = module.factory;",
    "    var dependencyMap = module.dependencyMap;",
    ...(hmr
      ? [
          "    moduleObject.hot = module.hot;",
          "    var Refresh = requireRefresh();",
          '    var refreshPrefix = global.__METRO_GLOBAL_PREFIX__ || "";',
          "    var prevRefreshReg = global.$RefreshReg$;",
          "    var prevRefreshSig = global.$RefreshSig$;",
          "    if (Refresh != null) {",
          "      global.$RefreshReg$ = function (type, id) {",
          '        Refresh.register(type, refreshPrefix + " " + moduleId + " " + id);',
          "      };",
          "      global.$RefreshSig$ = Refresh.createSignatureFunctionForTransform;",
          "    }",
        ]
      : []),
    "    try {",
    "      factory(",
    "        global,",
    "        metroRequire,",
    "        metroImportDefault,",
    "        metroImportAll,",
    "        moduleObject,",
    "        moduleObject.exports,",
    "        dependencyMap,",
    "      );",
    ...(hmr
      ? [
          "      if (Refresh != null) {",
          "        registerExportsForReactRefresh(",
          "          Refresh,",
          "          moduleObject.exports,",
          '          refreshPrefix + " " + moduleId,',
          "        );",
          "      }",
          "      return moduleObject.exports;",
          "    } catch (error) {",
          "      module.hasError = true;",
          "      module.error = error;",
          "      module.isInitialized = false;",
          "      module.publicModule.exports = undefined;",
          "      throw error;",
          "    } finally {",
          "      global.$RefreshReg$ = prevRefreshReg;",
          "      global.$RefreshSig$ = prevRefreshSig;",
          "    }",
        ]
      : [
          "      module.factory = undefined;",
          "      module.dependencyMap = undefined;",
          "      return moduleObject.exports;",
          "    } catch (error) {",
          "      module.isInitialized = false;",
          "      module.hasError = true;",
          "      module.error = error;",
          "      module.publicModule = { exports: {} };",
          "      throw error;",
          "    }",
        ]),
    "  }",
    "",
    "  function clear() {",
    "    modules = Object.create(null);",
    "  }",
    "",
    "  metroRequire.importDefault = metroImportDefault;",
    "  metroRequire.importAll = metroImportAll;",
    ...(hmr ? buildHmrRuntimeLines() : []),
    "",
    "  global.__d = define;",
    "  global.__r = metroRequire;",
    "  global.__c = clear;",
    "})(",
    '  typeof globalThis !== "undefined"',
    "    ? globalThis",
    '    : typeof global !== "undefined"',
    "      ? global",
    "      : this",
    ");",
    "",
  ].join("\n");
}

/**
 * The Fast Refresh engine, ported faithfully from
 * `metro-runtime/src/polyfills/require.js` and adapted to Vifx's object-backed
 * `modules` registry and ES5 (`var`/`function`) prelude style. Returned as the
 * runtime body lines spliced into {@link buildModuleRegistryPrelude} when
 * `hmr: true`. Every function closes over the prelude's `modules`, `EMPTY`,
 * `metroRequire` and friends, so it must stay inside the prelude IIFE.
 */
function buildHmrRuntimeLines(): string[] {
  return [
    "",
    "  var reactRefreshTimeout = null;",
    "  var CYCLE_DETECTED = {};",
    "",
    "  function createHotReloadingObject() {",
    "    var hot = {",
    "      _acceptCallback: null,",
    "      _disposeCallback: null,",
    "      _didAccept: false,",
    "      accept: function (callback) {",
    "        hot._didAccept = true;",
    "        hot._acceptCallback = callback;",
    "      },",
    "      dispose: function (callback) {",
    "        hot._disposeCallback = callback;",
    "      },",
    "    };",
    "    return hot;",
    "  }",
    "",
    "  function requireRefresh() {",
    '    var prefix = global.__METRO_GLOBAL_PREFIX__ || "";',
    '    return global[prefix + "__ReactRefresh"] || metroRequire.Refresh || null;',
    "  }",
    "",
    "  // Updates 'bubble' up the inverse-dependency tree to the closest accepted",
    "  // parent. Returns silently after scheduling a full refresh when nothing",
    "  // along the way accepts the update.",
    "  function metroHotUpdateModule(id, factory, dependencyMap, inverseDependencies) {",
    "    var mod = modules[id];",
    "    if (mod == null) {",
    "      if (factory) {",
    "        return;",
    "      }",
    "      throw new Error('Requiring unknown module \"' + id + '\".');",
    "    }",
    "    if (!mod.hasError && !mod.isInitialized) {",
    "      // The module hasn't executed yet, so it is always safe to replace.",
    "      mod.factory = factory;",
    "      mod.dependencyMap = dependencyMap;",
    "      return;",
    "    }",
    "    var Refresh = requireRefresh();",
    "    var refreshBoundaryIDs = new Set();",
    "    var didBailOut = false;",
    "    var updatedModuleIDs;",
    "    try {",
    "      updatedModuleIDs = topologicalSort(",
    "        [id],",
    "        function (pendingID) {",
    "          var pendingModule = modules[pendingID];",
    "          if (pendingModule == null) {",
    "            return [];",
    "          }",
    "          var pendingHot = pendingModule.hot;",
    "          if (pendingHot == null) {",
    "            throw new Error('[Refresh] Expected module.hot to always exist in DEV.');",
    "          }",
    "          var canAccept = pendingHot._didAccept;",
    "          if (!canAccept && Refresh != null) {",
    "            var isBoundary = isReactRefreshBoundary(",
    "              Refresh,",
    "              pendingModule.publicModule.exports,",
    "            );",
    "            if (isBoundary) {",
    "              canAccept = true;",
    "              refreshBoundaryIDs.add(pendingID);",
    "            }",
    "          }",
    "          if (canAccept) {",
    "            return [];",
    "          }",
    "          var parentIDs = inverseDependencies[pendingID];",
    "          if (parentIDs == null || parentIDs.length === 0) {",
    "            performFullRefresh('No root boundary');",
    "            didBailOut = true;",
    "            return [];",
    "          }",
    "          return parentIDs;",
    "        },",
    "        function () {",
    "          return didBailOut;",
    "        },",
    "      ).reverse();",
    "    } catch (e) {",
    "      if (e === CYCLE_DETECTED) {",
    "        performFullRefresh('Dependency cycle');",
    "        return;",
    "      }",
    "      throw e;",
    "    }",
    "    if (didBailOut) {",
    "      return;",
    "    }",
    "    var seenModuleIDs = new Set();",
    "    for (var i = 0; i < updatedModuleIDs.length; i++) {",
    "      var updatedID = updatedModuleIDs[i];",
    "      if (seenModuleIDs.has(updatedID)) {",
    "        continue;",
    "      }",
    "      seenModuleIDs.add(updatedID);",
    "      var updatedMod = modules[updatedID];",
    "      if (updatedMod == null) {",
    "        throw new Error('[Refresh] Expected to find the updated module.');",
    "      }",
    "      var prevExports = updatedMod.publicModule.exports;",
    "      var didError = runUpdatedModule(",
    "        updatedID,",
    "        updatedID === id ? factory : undefined,",
    "        updatedID === id ? dependencyMap : undefined,",
    "      );",
    "      var nextExports = updatedMod.publicModule.exports;",
    "      if (didError) {",
    "        return;",
    "      }",
    "      if (refreshBoundaryIDs.has(updatedID)) {",
    "        var isNoLongerABoundary = !isReactRefreshBoundary(Refresh, nextExports);",
    "        var didInvalidate = shouldInvalidateReactRefreshBoundary(",
    "          Refresh,",
    "          prevExports,",
    "          nextExports,",
    "        );",
    "        if (isNoLongerABoundary || didInvalidate) {",
    "          var parentIDs = inverseDependencies[updatedID];",
    "          if (parentIDs == null || parentIDs.length === 0) {",
    "            performFullRefresh(",
    "              isNoLongerABoundary ? 'No longer a boundary' : 'Invalidated boundary',",
    "            );",
    "            return;",
    "          }",
    "          for (var j = 0; j < parentIDs.length; j++) {",
    "            var parentID = parentIDs[j];",
    "            var parentMod = modules[parentID];",
    "            if (parentMod == null) {",
    "              throw new Error('[Refresh] Expected to find parent module.');",
    "            }",
    "            var canAcceptParent = isReactRefreshBoundary(",
    "              Refresh,",
    "              parentMod.publicModule.exports,",
    "            );",
    "            if (canAcceptParent) {",
    "              refreshBoundaryIDs.add(parentID);",
    "              updatedModuleIDs.push(parentID);",
    "            } else {",
    "              performFullRefresh('Invalidated boundary');",
    "              return;",
    "            }",
    "          }",
    "        }",
    "      }",
    "    }",
    "    if (Refresh != null) {",
    "      // Debounce: __accept may fire several times for one delta.",
    "      if (reactRefreshTimeout == null) {",
    "        reactRefreshTimeout = setTimeout(function () {",
    "          reactRefreshTimeout = null;",
    "          Refresh.performReactRefresh();",
    "        }, 30);",
    "      }",
    "    }",
    "  }",
    "",
    "  function topologicalSort(roots, getEdges, earlyStop) {",
    "    var result = [];",
    "    var visited = new Set();",
    "    var stack = new Set();",
    "    function traverseDependentNodes(node) {",
    "      if (stack.has(node)) {",
    "        throw CYCLE_DETECTED;",
    "      }",
    "      if (visited.has(node)) {",
    "        return;",
    "      }",
    "      visited.add(node);",
    "      stack.add(node);",
    "      var dependentNodes = getEdges(node);",
    "      if (earlyStop(node)) {",
    "        stack.delete(node);",
    "        return;",
    "      }",
    "      dependentNodes.forEach(function (dependent) {",
    "        traverseDependentNodes(dependent);",
    "      });",
    "      stack.delete(node);",
    "      result.push(node);",
    "    }",
    "    roots.forEach(function (root) {",
    "      traverseDependentNodes(root);",
    "    });",
    "    return result;",
    "  }",
    "",
    "  function runUpdatedModule(id, factory, dependencyMap) {",
    "    var mod = modules[id];",
    "    if (mod == null) {",
    "      throw new Error('[Refresh] Expected to find the module.');",
    "    }",
    "    var hot = mod.hot;",
    "    if (!hot) {",
    "      throw new Error('[Refresh] Expected module.hot to always exist in DEV.');",
    "    }",
    "    if (hot._disposeCallback) {",
    "      try {",
    "        hot._disposeCallback();",
    "      } catch (error) {",
    "        console.error('Error while calling dispose handler for module ' + id + ': ', error);",
    "      }",
    "    }",
    "    if (factory) {",
    "      mod.factory = factory;",
    "    }",
    "    if (dependencyMap) {",
    "      mod.dependencyMap = dependencyMap;",
    "    }",
    "    mod.hasError = false;",
    "    mod.error = undefined;",
    "    mod.importedAll = EMPTY;",
    "    mod.importedDefault = EMPTY;",
    "    mod.isInitialized = false;",
    "    var prevExports = mod.publicModule.exports;",
    "    mod.publicModule.exports = {};",
    "    hot._didAccept = false;",
    "    hot._acceptCallback = null;",
    "    hot._disposeCallback = null;",
    "    metroRequire(id);",
    "    if (mod.hasError) {",
    "      // Keep the last good exports alive under the redbox so the rest of the",
    "      // app survives until the user fixes the error.",
    "      mod.hasError = false;",
    "      mod.isInitialized = true;",
    "      mod.error = null;",
    "      mod.publicModule.exports = prevExports;",
    "      return true;",
    "    }",
    "    if (hot._acceptCallback) {",
    "      try {",
    "        hot._acceptCallback();",
    "      } catch (error) {",
    "        console.error('Error while calling accept handler for module ' + id + ': ', error);",
    "      }",
    "    }",
    "    return false;",
    "  }",
    "",
    "  function performFullRefresh(reason) {",
    "    var Refresh = requireRefresh();",
    "    if (Refresh != null && typeof Refresh.performFullRefresh === 'function') {",
    "      Refresh.performFullRefresh('Fast Refresh - ' + reason);",
    "    } else if (typeof global.__vifxFullReload === 'function') {",
    "      global.__vifxFullReload(reason);",
    "    } else {",
    "      console.warn('[Fast Refresh] Could not reload after an edit: ' + reason);",
    "    }",
    "  }",
    "",
    "  function isExportSafeToAccess(moduleExports, key) {",
    "    return (",
    "      (moduleExports && moduleExports.__esModule) ||",
    "      (Object.getOwnPropertyDescriptor(moduleExports, key) || {}).get == null",
    "    );",
    "  }",
    "",
    "  // Modules that only export components become React Refresh boundaries.",
    "  function isReactRefreshBoundary(Refresh, moduleExports) {",
    "    if (Refresh.isLikelyComponentType(moduleExports)) {",
    "      return true;",
    "    }",
    "    if (moduleExports == null || typeof moduleExports !== 'object') {",
    "      return false;",
    "    }",
    "    var hasExports = false;",
    "    var areAllExportsComponents = true;",
    "    for (var key in moduleExports) {",
    "      hasExports = true;",
    "      if (key === '__esModule') {",
    "        continue;",
    "      }",
    "      if (!isExportSafeToAccess(moduleExports, key)) {",
    "        return false;",
    "      }",
    "      var exportValue = moduleExports[key];",
    "      if (!Refresh.isLikelyComponentType(exportValue)) {",
    "        areAllExportsComponents = false;",
    "      }",
    "    }",
    "    return hasExports && areAllExportsComponents;",
    "  }",
    "",
    "  function shouldInvalidateReactRefreshBoundary(Refresh, prevExports, nextExports) {",
    "    var prevSignature = getRefreshBoundarySignature(Refresh, prevExports);",
    "    var nextSignature = getRefreshBoundarySignature(Refresh, nextExports);",
    "    if (prevSignature.length !== nextSignature.length) {",
    "      return true;",
    "    }",
    "    for (var i = 0; i < nextSignature.length; i++) {",
    "      if (prevSignature[i] !== nextSignature[i]) {",
    "        return true;",
    "      }",
    "    }",
    "    return false;",
    "  }",
    "",
    "  function getRefreshBoundarySignature(Refresh, moduleExports) {",
    "    var signature = [];",
    "    signature.push(Refresh.getFamilyByType(moduleExports));",
    "    if (moduleExports == null || typeof moduleExports !== 'object') {",
    "      return signature;",
    "    }",
    "    for (var key in moduleExports) {",
    "      if (key === '__esModule') {",
    "        continue;",
    "      }",
    "      if (!isExportSafeToAccess(moduleExports, key)) {",
    "        continue;",
    "      }",
    "      var exportValue = moduleExports[key];",
    "      signature.push(key);",
    "      signature.push(Refresh.getFamilyByType(exportValue));",
    "    }",
    "    return signature;",
    "  }",
    "",
    "  function registerExportsForReactRefresh(Refresh, moduleExports, moduleID) {",
    "    Refresh.register(moduleExports, moduleID + ' %exports%');",
    "    if (moduleExports == null || typeof moduleExports !== 'object') {",
    "      return;",
    "    }",
    "    for (var key in moduleExports) {",
    "      if (!isExportSafeToAccess(moduleExports, key)) {",
    "        continue;",
    "      }",
    "      var exportValue = moduleExports[key];",
    "      var typeID = moduleID + ' %exports% ' + key;",
    "      Refresh.register(exportValue, typeID);",
    "    }",
    "  }",
    "",
    "  metroRequire.Refresh = null;",
    "  metroRequire.getModules = function () {",
    "    return modules;",
    "  };",
    "  global.__accept = metroHotUpdateModule;",
  ];
}

/**
 * The lean production runtime prelude (no Fast Refresh). Kept as a stable
 * exported constant: the serializer prepends it and tests assert the bundle
 * starts with exactly this string.
 */
export const MODULE_REGISTRY_PRELUDE = buildModuleRegistryPrelude();
