import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { loadVifxConfig } from "@vifx/config";
import { expect, test } from "vite-plus/test";
import type { MetroConfigFixes } from "../src/lib/metro-config.ts";
import { applyMetroFixesToVifxConfig } from "../src/lib/vifx-config-edit.ts";

const DEFAULTS = {
  assetExtensions: ["png", "jpg"],
  extensions: ["tsx", "ts", "jsx", "js", "json"],
};

const FIXES: MetroConfigFixes = {
  aliases: { shared: "../shared" },
  assetExtensions: ["lottie"],
  sourceExtensions: ["mdx"],
};

async function writeConfig(contents: string): Promise<string> {
  const projectRoot = await mkdtemp(path.join(os.tmpdir(), "vifx-config-edit-"));
  const configPath = path.join(projectRoot, "vifx.config.ts");
  await writeFile(configPath, contents, "utf8");
  return configPath;
}

// The shape `vifx setup` writes, with its inline arrays and trailing commas.
const GENERATED_CONFIG = [
  "// Generated by @vifx/codemods for a bounded Expo migration-first setup.",
  "export default {",
  "  projectRoot: process.cwd(),",
  '  projectType: "expo",',
  "  vite: {",
  '    mode: "expo",',
  "    targets: [",
  "      {",
  '        platform: "ios",',
  '        entry: "./index.js",',
  "        hermes: false,",
  "      },",
  "      {",
  '        platform: "android",',
  '        entry: "./index.js",',
  "        hermes: false,",
  "      },",
  "    ],",
  "  },",
  "  resolver: {",
  '    conditions: ["react-native", "import", "require", "default"],',
  "  },",
  "};",
  "",
].join("\n");

test("adds the mapped settings to a generated config and keeps the rest", async () => {
  const configPath = await writeConfig(GENERATED_CONFIG);

  const result = await applyMetroFixesToVifxConfig(configPath, FIXES, DEFAULTS);
  const written = await readFile(configPath, "utf8");

  expect(result.applied).toEqual([
    "resolver.extensions: + mdx",
    "resolver.assetExtensions: + lottie",
    "vite.targets[].aliases: + shared",
  ]);
  expect(result.manual).toEqual([]);
  expect(written).toContain("// Generated by @vifx/codemods");
  expect(written).toContain('conditions: ["react-native", "import", "require", "default"],');
  expect(written).toContain('    extensions: ["tsx", "ts", "jsx", "js", "json", "mdx"],');
  expect(written).toContain('    assetExtensions: ["png", "jpg", "lottie"],');
  expect(written.match(/aliases: \{ "shared": "\.\.\/shared" \},/gu)).toHaveLength(2);

  const loaded = await loadVifxConfig({ cwd: path.dirname(configPath), optional: false });
  expect(loaded.config.resolver.extensions).toContain("mdx");
  expect(loaded.config.resolver.assetExtensions).toContain("lottie");
  expect(loaded.config.vite.targets.map((target) => target.aliases)).toEqual([
    { shared: "../shared" },
    { shared: "../shared" },
  ]);
});

test("a second run changes nothing", async () => {
  const configPath = await writeConfig(GENERATED_CONFIG);
  await applyMetroFixesToVifxConfig(configPath, FIXES, DEFAULTS);
  const once = await readFile(configPath, "utf8");

  const result = await applyMetroFixesToVifxConfig(configPath, FIXES, DEFAULTS);

  expect(result.applied).toEqual([]);
  expect(await readFile(configPath, "utf8")).toBe(once);
});

test("merges into existing lists and alias maps of a defineVifxConfig call", async () => {
  const configPath = await writeConfig(
    [
      'import { defineVifxConfig } from "@vifx/config";',
      "",
      "export default defineVifxConfig({",
      "  resolver: {",
      '    extensions: ["ts", "tsx", "js"]',
      "  },",
      "  vite: {",
      "    targets: [",
      '      { platform: "ios", entry: "./index.js", hermes: false, aliases: { "@": "./src" } },',
      "    ],",
      "  },",
      "});",
      "",
    ].join("\n"),
  );

  const result = await applyMetroFixesToVifxConfig(configPath, FIXES, DEFAULTS);
  const written = await readFile(configPath, "utf8");

  expect(result.manual).toEqual([]);
  expect(written).toContain('extensions: ["ts", "tsx", "js", "mdx"],');
  expect(written).toContain('assetExtensions: ["png", "jpg", "lottie"]');
  expect(written).toContain('aliases: { "@": "./src", "shared": "../shared" }');
});

test("adds a resolver section when the config has none", async () => {
  const configPath = await writeConfig(
    [
      "const config = {",
      '  projectType: "react-native",',
      "};",
      "",
      "export default config;",
      "",
    ].join("\n"),
  );

  const result = await applyMetroFixesToVifxConfig(
    configPath,
    { aliases: {}, assetExtensions: [], sourceExtensions: ["mdx"] },
    DEFAULTS,
  );
  const written = await readFile(configPath, "utf8");

  expect(result.applied).toEqual(["resolver.extensions: + mdx"]);
  expect(written).toContain(
    [
      '  projectType: "react-native",',
      "  resolver: {",
      '    extensions: ["tsx", "ts", "jsx", "js", "json", "mdx"],',
      "  },",
    ].join("\n"),
  );
});

test("leaves what it cannot edit safely to the user", async () => {
  const source = [
    'const base = ["ts", "js"];',
    "export default {",
    "  resolver: { extensions: [...base] },",
    "};",
    "",
  ].join("\n");
  const configPath = await writeConfig(source);

  const result = await applyMetroFixesToVifxConfig(configPath, FIXES, DEFAULTS);

  expect(result.manual).toEqual([
    "resolver.extensions: add mdx (the list is not a plain array)",
    "vite.targets[].aliases: add shared (vite.targets is not a list of object literals)",
  ]);
  expect(result.applied).toEqual(["resolver.assetExtensions: + lottie"]);
  expect(await readFile(configPath, "utf8")).toContain("extensions: [...base]");
});
